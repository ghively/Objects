import { Icon as IconifyIcon } from '@iconify/react'
import type { IconifyIcon as IconData, IconifyJSON } from '@iconify/types'
import { getIconData } from '@iconify/utils'
import { useEffect, useState } from 'react'
import type { Icon as IconValue } from '@/api/types'
import { appIcons } from '@/icons/appIcons'

// Icons are bundled (Phosphor via @iconify-json/ph, VS Code file icons via
// @iconify-json/vscode-icons) and never fetched over the network: we hand <Icon>
// the icon data object, so Iconify's API loader is never used.
//
// The app's own Phosphor icons (`src/icons/appIcons.ts`, generated by `scripts/app-icons.mjs`)
// are in the entry and drawn synchronously; the full sets (4.4 MB for Phosphor) load on demand,
// for the icon picker and for icons users chose. An icon once drawn from a full set is remembered
// in localStorage, so the next start draws it at once too (audit 2026-11-01 F3).

const LOADERS: Record<string, () => Promise<unknown>> = {
  ph: () => import('@iconify-json/ph/icons.json'),
  'vscode-icons': () => import('@iconify-json/vscode-icons/icons.json'),
}

/** The subsets in the entry, by prefix. */
const SUBSETS: Record<string, IconifyJSON> = { ph: appIcons }

/** Bundled prefixes, longest first, so `vscode-icons-…` never matches a shorter prefix. */
const PREFIXES = Object.keys(LOADERS).sort((a, b) => b.length - a.length)

const FALLBACK_PREFIX = 'ph'
const FALLBACK_NAME = 'cube'

const collections = new Map<string, IconifyJSON>()
const loading = new Map<string, Promise<IconifyJSON>>()

function loadCollection(prefix: string): Promise<IconifyJSON> {
  const have = collections.get(prefix)
  if (have) return Promise.resolve(have)
  let p = loading.get(prefix)
  if (!p) {
    p = LOADERS[prefix]().then((m) => {
      const json = ((m as { default?: IconifyJSON }).default ?? m) as IconifyJSON
      collections.set(prefix, json)
      return json
    })
    loading.set(prefix, p)
  }
  return p
}

// ---- remembered icons (a per-viewer convenience; storage may be missing or full) -------------

const REMEMBER_KEY = 'object.icons'
const REMEMBER_MAX = 400
let remembered: Record<string, IconData> | null = null

function rememberedIcons(): Record<string, IconData> {
  if (remembered) return remembered
  remembered = {}
  try {
    const parsed = JSON.parse(localStorage.getItem(REMEMBER_KEY) ?? 'null') as unknown
    if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) remembered = parsed as Record<string, IconData>
  } catch {
    /* no storage, or not ours */
  }
  return remembered
}

function remember(key: string, data: IconData): void {
  const all = rememberedIcons()
  if (all[key]) return
  all[key] = data
  const keys = Object.keys(all)
  for (const k of keys.slice(0, Math.max(0, keys.length - REMEMBER_MAX))) delete all[k]
  try {
    localStorage.setItem(REMEMBER_KEY, JSON.stringify(all))
  } catch {
    /* storage unavailable: drawn from the full set each start */
  }
}

/** Forget the remembered icons (tests). */
export function forgetRememberedIcons(): void {
  remembered = null
  try {
    localStorage.removeItem(REMEMBER_KEY)
  } catch {
    /* ignore */
  }
}

/** `{prefix, name}` for an Iconify id, or `prefix: null` when its prefix isn't bundled. */
export function parseIconId(id: string): { prefix: string | null; name: string } {
  for (const prefix of PREFIXES) {
    if (id.startsWith(`${prefix}-`) || id.startsWith(`${prefix}:`)) {
      return { prefix, name: id.slice(prefix.length + 1) }
    }
  }
  if (id.includes(':')) return { prefix: null, name: id }
  // A bare name ("check-circle") is a Phosphor icon, as in M1.
  return { prefix: 'ph', name: id }
}

/** "ph-check-circle", "ph:check-circle" or "check-circle" → "check-circle". */
export function phName(name: string): string {
  return name.replace(/^ph[-:]/, '')
}

/** True for an Iconify id (`ph-…`, `vscode-icons:…`), false for an emoji or other text. */
export function isIconifyId(s: string): boolean {
  return /^[a-z0-9]+(?:-[a-z0-9]+)*[:-][a-z0-9]/i.test(s)
}

/** The icon id or emoji to render: an `Icon`'s `val`, a string as is, or `fallback` when empty. */
export function iconName(icon: IconValue | string | null | undefined, fallback: string): string {
  const v = typeof icon === 'string' ? icon : icon?.val
  return v && v.trim() ? v : fallback
}

export interface ResolvedIcon {
  data: IconData
  /** `prefix:name` of the icon actually drawn. */
  resolved: string
  fallback: boolean
}

/**
 * Icon data at hand without loading anything: the subset, a remembered icon, a loaded full set
 * (an icon found there is remembered, so the next start has it before the set loads).
 */
function dataAtHand(prefix: string, name: string): IconData | null {
  const subset = SUBSETS[prefix]
  if (subset) {
    const d = getIconData(subset, name)
    if (d) return d
  }
  const key = `${prefix}:${name}`
  const r = rememberedIcons()[key]
  if (r) return r
  const json = collections.get(prefix)
  const d = json ? getIconData(json, name) : null
  if (d) remember(key, d)
  return d
}

/**
 * The icon for `id` without loading anything: its data, the fallback (`ph-cube`) when the id can
 * have no data (no bundled prefix, or not in its loaded set), or undefined while its full set has
 * yet to load and may hold it.
 */
export function resolveIconSync(id: string): ResolvedIcon | null | undefined {
  const { prefix, name } = parseIconId(id)
  if (prefix) {
    const data = dataAtHand(prefix, name)
    if (data) return { data, resolved: `${prefix}:${name}`, fallback: false }
    if (!collections.has(prefix)) return undefined
  }
  const data = dataAtHand(FALLBACK_PREFIX, FALLBACK_NAME)
  return data ? { data, resolved: `${FALLBACK_PREFIX}:${FALLBACK_NAME}`, fallback: true } : null
}

/**
 * The icon for `id`: what is at hand (the subset, a remembered icon, a loaded set) without loading
 * anything, else its full set is loaded first (`dataAtHand` remembers a find).
 */
export async function resolveIcon(id: string): Promise<ResolvedIcon | null> {
  const atHand = resolveIconSync(id)
  if (atHand !== undefined) return atHand
  const { prefix } = parseIconId(id)
  if (prefix) await loadCollection(prefix)
  return resolveIconSync(id) ?? null
}

/**
 * An `Icon` value or a frontmatter icon string: an Iconify id renders as an icon, anything else
 * (an emoji) as text. Nothing (and no fallback) renders nothing.
 */
export function IconOrEmoji({
  icon,
  size,
  fallback,
  className,
}: {
  icon: IconValue | string | null | undefined
  size: number
  fallback?: string
  className?: string
}) {
  const val = iconName(icon, fallback ?? '')
  if (!val) return null
  const emoji = typeof icon === 'object' && icon && icon.val.trim() ? icon.type === 'emoji' : !isIconifyId(val)
  if (!emoji) return <Icon name={val} size={size} className={className} />
  return (
    <span aria-hidden className={className} style={{ fontSize: size, lineHeight: 1 }}>
      {val}
    </span>
  )
}

export interface IconProps {
  /** Any Iconify id with a bundled prefix (`ph`, `vscode-icons`); anything else renders `ph-cube`. */
  name: string
  size?: number
  className?: string
}

export function Icon({ name, size = 16, className }: IconProps) {
  const [state, setState] = useState<{ name: string; r: ResolvedIcon | null } | null>(() => {
    const r = resolveIconSync(name)
    return r === undefined ? null : { name, r }
  })

  useEffect(() => {
    let alive = true
    const r = resolveIconSync(name)
    if (r !== undefined) {
      setState({ name, r })
      return
    }
    void resolveIcon(name).then((res) => {
      if (alive) setState({ name, r: res })
    })
    return () => {
      alive = false
    }
  }, [name])

  const r = state && state.name === name ? state.r : null
  if (!r) {
    return (
      <span
        aria-hidden
        data-icon={name}
        className={className}
        style={{ display: 'inline-block', width: size, height: size }}
      />
    )
  }
  return (
    <IconifyIcon
      icon={r.data}
      // The data is in hand: draw on the first render (Iconify otherwise renders a bare <span> first).
      ssr
      width={size}
      height={size}
      className={className}
      aria-hidden
      data-icon={name}
      data-resolved={r.resolved}
      {...(r.fallback ? { title: name } : {})}
    />
  )
}
