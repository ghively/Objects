#!/usr/bin/env node
// Generates `src/icons/appIcons.ts`: the subset of the bundled Phosphor set (`@iconify-json/ph`)
// that the app's own code references (every `ph-…` id in `src/`, tests aside, plus the `ph-cube`
// fallback), so the shell draws its icons synchronously from ~75 KB instead of loading the whole
// 4.4 MB set on the start-up path (audit 2026-11-01 F3). The full set stays a lazy chunk for the
// icon picker and for icons users choose. Deterministic: sorted ids, stable JSON.
//
//   node scripts/app-icons.mjs            # write src/icons/appIcons.ts
//   node scripts/app-icons.mjs --check    # exit 1 when the file is out of date
//
// `src/icons/appIcons.test.ts` runs the same build in-process and compares, so a missing id
// fails the test gate before it reaches a build.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const FRONTEND = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(FRONTEND, 'src', 'icons', 'appIcons.ts')
/** Always in the subset: what `<Icon>` draws for an id it has no data for. */
export const FALLBACK = 'cube'

const ID = /\bph[-:]([a-z0-9]+(?:-[a-z0-9]+)*)/g

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) {
      if (name === 'node_modules' || name === '__fixtures__') continue
      walk(full, out)
    } else if (/\.(ts|tsx)$/.test(name) && !/\.test\.(ts|tsx)$/.test(name)) out.push(full)
  }
  return out
}

/** Every `ph-…` / `ph:…` id written in `src/` (not the tests, not the generated file), sorted. */
export function referencedPhIds(srcDir = join(FRONTEND, 'src')) {
  const ids = new Set([FALLBACK])
  for (const file of walk(srcDir)) {
    if (relative(srcDir, file).split('\\').join('/') === 'icons/appIcons.ts') continue
    for (const m of readFileSync(file, 'utf8').matchAll(ID)) ids.add(m[1])
  }
  return [...ids].sort()
}

/** The Phosphor set (`@iconify-json/ph/icons.json`), read from disk. */
export function loadPhosphor() {
  const require = createRequire(join(FRONTEND, 'package.json'))
  return JSON.parse(readFileSync(require.resolve('@iconify-json/ph/icons.json'), 'utf8'))
}

/**
 * The subset as an `IconifyJSON`: `prefix`, the set's dimensions, the referenced icons (and
 * aliases, with their parents) in sorted order. Ids the set does not have (a `ph-` in a
 * comment, a dynamic prefix) are left out and returned in `missing`.
 */
export async function buildSubset(full, ids) {
  const { getIcons } = await import('@iconify/utils')
  const subset = getIcons(full, ids, true)
  const missing = subset?.not_found ?? []
  const sortKeys = (o) => Object.fromEntries(Object.keys(o ?? {}).sort().map((k) => [k, o[k]]))
  const out = { prefix: full.prefix, lastModified: full.lastModified, icons: sortKeys(subset?.icons) }
  if (subset?.aliases && Object.keys(subset.aliases).length > 0) out.aliases = sortKeys(subset.aliases)
  for (const k of ['width', 'height', 'left', 'top']) if (full[k] !== undefined) out[k] = full[k]
  return { subset: out, missing }
}

/** The generated module's text (one icon per line, so a diff shows what came and went). */
export function render(subset) {
  const lines = Object.entries(subset.icons).map(([name, data]) => `    ${JSON.stringify(name)}: ${JSON.stringify(data)},`)
  const aliases = Object.entries(subset.aliases ?? {}).map(([name, data]) => `    ${JSON.stringify(name)}: ${JSON.stringify(data)},`)
  const dims = ['width', 'height', 'left', 'top'].filter((k) => subset[k] !== undefined).map((k) => `  ${k}: ${JSON.stringify(subset[k])},`)
  return [
    '// GENERATED by scripts/app-icons.mjs (audit 2026-11-01 F3): the Phosphor icons the app itself',
    '// uses, drawn synchronously; the full set stays lazy. Do not edit: run `node scripts/app-icons.mjs`.',
    "import type { IconifyJSON } from '@iconify/types'",
    '',
    'export const appIcons: IconifyJSON = {',
    `  prefix: ${JSON.stringify(subset.prefix)},`,
    ...(subset.lastModified !== undefined ? [`  lastModified: ${JSON.stringify(subset.lastModified)},`] : []),
    ...dims,
    '  icons: {',
    ...lines,
    '  },',
    ...(aliases.length > 0 ? ['  aliases: {', ...aliases, '  },'] : []),
    '}',
    '',
  ].join('\n')
}

export async function generate() {
  const ids = referencedPhIds()
  const { subset, missing } = await buildSubset(loadPhosphor(), ids)
  return { text: render(subset), ids, missing, count: Object.keys(subset.icons).length }
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const { text, missing, count } = await generate()
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUT, 'utf8')
    } catch {
      /* missing: out of date */
    }
    if (current !== text) {
      console.error(`src/icons/appIcons.ts is out of date: run node scripts/app-icons.mjs`)
      process.exit(1)
    }
    console.log(`src/icons/appIcons.ts is current (${count} icons)`)
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote src/icons/appIcons.ts: ${count} icons${missing.length ? `; not in the set: ${missing.join(', ')}` : ''}`)
  }
}
