export function getColorValue<T extends keyof typeof colors>(tone: T, value: string) {
  return colors[tone][value as keyof (typeof colors)[T]]
}

export function oklchToRgb(color: string): string {
  const match = color.match(/oklch\(\s*([^)]+)\)/i)
  if (!match) return color

  const parts = match[1]
    .replace(/\//g, ' ')
    .trim()
    .split(/[\s,]+/)

  const parseComponent = (value: string | undefined, scale: number): number => {
    if (value === undefined) return 0
    const isPercent = value.endsWith('%')
    const parsed = parseFloat(value)
    if (Number.isNaN(parsed)) return 0
    return isPercent ? (parsed / 100) * scale : parsed
  }

  const lightness = parseComponent(parts[0], 1)
  const chroma = parseComponent(parts[1], 0.4)
  const hueDeg = parseComponent(parts[2], 1)
  const hueRad = (hueDeg * Math.PI) / 180

  const a = chroma * Math.cos(hueRad)
  const b = chroma * Math.sin(hueRad)

  const l_ = lightness + 0.3963377774 * a + 0.2158037573 * b
  const m_ = lightness - 0.1055613458 * a - 0.0638541728 * b
  const s_ = lightness - 0.0894841775 * a - 1.291485548 * b

  const l = l_ * l_ * l_
  const m = m_ * m_ * m_
  const s = s_ * s_ * s_

  const linearR = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
  const linearG = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
  const linearB = -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s

  const gammaCorrect = (channel: number): number => {
    const clamped = Math.min(Math.max(channel, 0), 1)
    return clamped <= 0.0031308 ? 12.92 * clamped : 1.055 * Math.pow(clamped, 1 / 2.4) - 0.055
  }

  const toHex = (channel: number): string =>
    Math.round(gammaCorrect(channel) * 255)
      .toString(16)
      .padStart(2, '0')

  return `#${toHex(linearR)}${toHex(linearG)}${toHex(linearB)}`
}
